/**
 * worker/obsidianMirror.ts — Human-Readable Markdown Note Generator for Obsidian
 *
 * Requirements:
 * - Approved teach recipes are exported to Obsidian as Markdown, but the Personal AI OS
 *   database remains the canonical source of truth for workflow state, versions, and approvals.
 * - Human-readable structure: title, status, origin, summary, steps, safety policy, approval history, tags, backlinks
 * - ZERO secrets, raw recordings, tokens, or credentials in exported Markdown
 */

import { WorkflowRecipeRecord } from './teachRecipeService';

export interface ObsidianNote {
  filename: string;
  vaultPath: string;
  markdown: string;
  recipeId: string;
  title: string;
}

export class ObsidianMirror {
  /**
   * Generates a formatted Markdown note for an approved recipe.
   */
  static formatRecipeNote(recipe: WorkflowRecipeRecord): ObsidianNote {
    const safeTitle = recipe.title.replace(/[/\\?%*:|"<>]/g, '-').trim();
    const filename = `${safeTitle}.md`;
    const vaultPath = `Workflows/${filename}`;

    const tags = ['workflow', 'skill', 'personal-ai-os', recipe.triggerType].join(', ');

    const stepsMarkdown = recipe.steps
      .map(
        (step) =>
          `### Step ${step.order}: ${step.description}\n` +
          `- **Adapter**: \`${step.adapter}\`\n` +
          `- **Action**: \`${step.action}\`\n` +
          `- **Target**: \`${step.target}\`\n` +
          (step.isOptional ? `- **Optional**: Yes\n` : '')
      )
      .join('\n');

    const markdown = `---
title: "${recipe.title}"
recipe_id: "${recipe.id}"
memory_id: "${recipe.memoryObjectId || 'unlinked'}"
status: "${recipe.status}"
origin: "teach_mode"
trigger_type: "${recipe.triggerType}"
confidence: ${recipe.confidence}
created_at: "${recipe.createdAt}"
approved_at: "${recipe.approvedAt || 'unapproved'}"
tags: [${tags}]
---

# ${recipe.title}

> **Personal AI OS Workflow Note**  
> *Approved teach recipes are exported to Obsidian as Markdown, but the Personal AI OS database remains the canonical source of truth for workflow state, versions, and approvals.*

## Summary
${recipe.intent}

- **Trigger**: \`${recipe.triggerType}\`
- **Confidence Rating**: ${(recipe.confidence * 100).toFixed(0)}%
- **OS Canonical Record**: \`os://memory/${recipe.memoryObjectId || recipe.id}\`

---

## Step-by-Step Procedure

${stepsMarkdown}

---

## Safety & Execution Policy
- **Approval Requirement**: Explicit owner confirmation required prior to execution.
- **Credential Safety**: No passwords, tokens, or private secrets stored in this note.
- **Boundary**: Execution operates only through typed adapters.

---
*Generated by Personal AI OS Obsidian Mirror on ${new Date().toISOString()}*
`;

    return {
      filename,
      vaultPath,
      markdown,
      recipeId: recipe.id,
      title: recipe.title,
    };
  }
}
